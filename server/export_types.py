"""Generate TypeScript DTOs from the implemented OpenAPI component schemas."""

import json
from pathlib import Path

from entourage_server.app import create_app


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(ts(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"({ts(schema['items'])})[]"
    if kind == "object":
        if "properties" not in schema:
            return "Record<string, unknown>"
        required = schema.get("required", [])
        fields = [f'{json.dumps(name)}{"" if name in required else "?"}: {ts(value)};'
                  for name, value in schema["properties"].items()]
        return "{ " + " ".join(fields) + " }"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


if __name__ == "__main__":
    schemas = create_app().openapi()["components"]["schemas"]
    output = "// Generated by server/export_types.py. Do not edit by hand.\n"
    output += "\n".join(f"export type {name} = {ts(schema)};" for name, schema in sorted(schemas.items())) + "\n"
    path = Path(__file__).resolve().parents[1] / "src" / "agent" / "serverTypes.ts"
    path.write_text(output, encoding="utf-8")
